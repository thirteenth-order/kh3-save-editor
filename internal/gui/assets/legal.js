export function legalPage() {
  const wrap = el("div", "legalpage");
  wrap.append(heading("i-shield", "Legal and attribution"));
  wrap.append(el("p", "lead",
    "What is and is not inside this program, in the order somebody would ask."));

  for (const sec of SECTIONS) {
    const box = el("section", "panel");
    const head = el("div", "panel-head");
    head.append(icon(sec.icon), el("h3", null, sec.title));
    box.append(head);
    for (const para of sec.body) box.append(el("p", "legal-p", para));
    wrap.append(box);
  }

  wrap.append(el("p", "ovempty",
    "If you represent a rights holder and believe something here is wrong, or " +
    "would prefer a mark or a name be removed, please open an issue on the " +
    "repository. Nothing in this project needs anybody's intellectual " +
    "property to work."));
  return wrap;
}
